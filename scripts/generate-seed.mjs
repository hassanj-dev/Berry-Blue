const palettes = [
  ["#5b4bdb", "#2f8cff"],
  ["#8b7cff", "#5aa9ff"],
  ["#2f8cff", "#5b4bdb"],
  ["#6f5cf0", "#38bdf8"],
];
const deviceSets = [
  ["mobile", "tablet", "desktop"],
  ["mobile", "desktop"],
  ["mobile"],
  ["desktop"],
];

function hash(text) {
  let h = 0;
  for (const ch of text) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h;
}

const slugify = (text) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const sql = (text) => "'" + String(text).replace(/'/g, "''") + "'";

function thumbSvg(slug) {
  const h = hash(slug);
  const [from, to] = palettes[h % palettes.length];
  const circles = [0, 1, 2]
    .map((i) => {
      const cx = 60 + ((h >>> (i * 4)) % 280);
      const cy = 60 + ((h >>> (i * 4 + 2)) % 280);
      const r = 40 + ((h >>> (i * 3)) % 70);
      return `<circle cx="${cx}" cy="${cy}" r="${r}" fill="#ffffff" fill-opacity="0.14" />`;
    })
    .join("");

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 400">` +
    `<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">` +
    `<stop offset="0" stop-color="${from}" /><stop offset="1" stop-color="${to}" />` +
    `</linearGradient></defs>` +
    `<rect width="400" height="400" fill="url(#g)" />${circles}</svg>`
  );
}

const thumbsDir = join("apps", "web", "public", "thumbs");
mkdirSync(thumbsDir, { recursive: true });

const categoryRows = [];
const gameRows = [];

for (const [slug, cat] of Object.entries(catalog)) {
  categoryRows.push(`(${sql(slug)}, ${sql(cat.name)})`);

  for (const title of cat.games) {
    const gameSlug = slugify(title);
    const h = hash(gameSlug);
    const tags = [cat.tags[h % cat.tags.length], cat.tags[(h + 1) % cat.tags.length]];
    const devices = deviceSets[h % deviceSets.length];
    const playCount = 100 + (h % 50000);
    const trending = (h >>> 3) % 1000;
    const daysAgo = h % 60;
    const description = `A fun ${cat.name.toLowerCase()} game. Placeholder text for testing.`;

    writeFileSync(join(thumbsDir, `${gameSlug}.svg`), thumbSvg(gameSlug));

    gameRows.push(
      `(${sql(gameSlug)}, ${sql(title)}, ${sql(description)}, ` +
        `${sql(`/thumbs/${gameSlug}.svg`)}, ${sql("/embed/demo.html")}, ` +
        `(select id from public.categories where slug = ${sql(slug)}), ` +
        `${sql(`{${tags.join(",")}}`)}::text[], ${sql(`{${devices.join(",")}}`)}::text[], ` +
        `'self-hosted', ${playCount}, ${trending}, now() - interval '${daysAgo} days', true)`,
    );
  }
}

const seed = [
  "-- Generated by scripts/generate-seed.mjs. Haath se edit na karein.",
  "insert into public.categories (slug, name) values",
  categoryRows.join(",\n"),
  "on conflict (slug) do nothing;",
  "",
  "insert into public.games (slug, title, description, thumbnail_url, embed_url, category_id, tags, devices, provider, play_count, trending_score, created_at, is_published) values",
  gameRows.join(",\n"),
  "on conflict (slug) do nothing;",
  "",
].join("\n");

writeFileSync(join("supabase", "seed.sql"), seed);
console.log(`Generated ${categoryRows.length} categories and ${gameRows.length} games.`);
